-- Core Inventory module tables (Prachiti). Every table is prefixed core_.

-- People and households -------------------------------------------------------

create table core_user (
    id           bigint generated by default as identity primary key,
    display_name varchar(100) not null,
    email        varchar(200) not null,
    created_at   timestamp with time zone not null,
    constraint core_user_email_uq unique (email)
);

create table core_household (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    invite_code varchar(12)  not null,
    created_at  timestamp with time zone not null,
    constraint core_household_invite_uq unique (invite_code)
);

-- One row per (household, user): a user can be in many households.
create table core_membership (
    id           bigint generated by default as identity primary key,
    household_id bigint      not null references core_household (id),
    user_id      bigint      not null references core_user (id),
    role         varchar(10) not null,
    joined_at    timestamp with time zone not null,
    constraint core_membership_uq unique (household_id, user_id)
);

create index core_membership_user_idx on core_membership (user_id);

-- Ingredient catalog ----------------------------------------------------------

-- household_id 0 means the shared catalog. Leftovers are household-scoped rows
-- with kind LEFTOVER, so "Dal" in one household is not "Dal" in another.
create table core_ingredient (
    id                 bigint generated by default as identity primary key,
    household_id       bigint       not null default 0,
    name               varchar(100) not null,
    kind               varchar(12)  not null,
    grams_each         numeric(12, 3),          -- average weight of one item; null when it is not counted
    grams_per_ml       numeric(8, 4),           -- density; null when it is not measured by volume
    default_location   varchar(10)  not null,
    shelf_days_pantry  integer,                 -- null: do not keep it there
    shelf_days_fridge  integer,
    shelf_days_freezer integer,
    constraint core_ingredient_name_uq unique (household_id, name)
);

create table core_ingredient_alias (
    id            bigint generated by default as identity primary key,
    ingredient_id bigint       not null references core_ingredient (id),
    alias         varchar(100) not null,
    constraint core_ingredient_alias_uq unique (alias)
);

-- Inventory -------------------------------------------------------------------

-- A lot is one purchase of one ingredient. It keeps its own price and expiry.
-- "version" is the optimistic lock: an update only succeeds if nobody else
-- changed the row since it was read.
create table core_lot (
    id               bigint generated by default as identity primary key,
    household_id     bigint         not null references core_household (id),
    ingredient_id    bigint         not null references core_ingredient (id),
    quantity         numeric(14, 3) not null,
    unit             varchar(5)     not null,
    unit_price       numeric(14, 6),            -- price of ONE unit; null when unknown
    location         varchar(10)    not null,
    expires_on       date,
    private_owner_id bigint references core_user (id),   -- null: shared with the household
    created_at       timestamp with time zone not null,
    version          bigint         not null,
    constraint core_lot_not_negative check (quantity >= 0)
);

create index core_lot_household_idx on core_lot (household_id, ingredient_id);
create index core_lot_expiry_idx on core_lot (expires_on);

-- One row per applied change (a confirmed proposal, a manual entry, an undo).
-- Rows are never updated or deleted. An undo is a NEW row that points at the
-- one it reverses; the unique constraint means a change can be undone once.
create table core_txn (
    id                bigint generated by default as identity primary key,
    household_id      bigint      not null references core_household (id),
    user_id           bigint      not null references core_user (id),
    kind              varchar(20) not null,
    pending_change_id bigint,
    dish_name         varchar(200),
    servings          integer,
    note              varchar(300),
    reverses_txn_id   bigint references core_txn (id),
    created_at        timestamp with time zone not null,
    constraint core_txn_reverses_uq unique (reverses_txn_id)
);

create index core_txn_household_idx on core_txn (household_id, id);

-- The append-only ledger: every quantity that ever moved, signed (+ in, - out).
-- The current quantity of a lot always equals the sum of its ledger rows.
create table core_ledger_entry (
    id            bigint generated by default as identity primary key,
    txn_id        bigint         not null references core_txn (id),
    household_id  bigint         not null,
    lot_id        bigint         not null references core_lot (id),
    ingredient_id bigint         not null,
    user_id       bigint         not null,
    type          varchar(12)    not null,
    delta         numeric(14, 3) not null,
    unit          varchar(5)     not null,
    unit_price    numeric(14, 6),
    created_at    timestamp with time zone not null
);

create index core_ledger_txn_idx on core_ledger_entry (txn_id);
create index core_ledger_lot_idx on core_ledger_entry (lot_id);
create index core_ledger_household_idx on core_ledger_entry (household_id, id);

-- Confirmation queue ----------------------------------------------------------

-- household_id and created_by are not foreign keys on purpose: proposals come
-- from the AI module before anyone has checked them. Membership is checked
-- when a user reads or decides a proposal.
create table core_pending_change (
    id           bigint generated by default as identity primary key,
    household_id bigint      not null,
    created_by   bigint      not null,
    source       varchar(12) not null,
    direction    varchar(4)  not null,
    dish_name    varchar(200),
    servings     integer,
    state        varchar(10) not null,
    submitted_at timestamp with time zone not null,
    edited_at    timestamp with time zone,
    decided_at   timestamp with time zone,
    decided_by   bigint,
    txn_id       bigint references core_txn (id),
    version      bigint      not null
);

create index core_pending_household_idx on core_pending_change (household_id, id);

create table core_pending_line (
    id                bigint generated by default as identity primary key,
    pending_change_id bigint  not null references core_pending_change (id),
    line_no           integer not null,
    raw_text          varchar(500),
    ingredient_id     bigint,
    quantity          numeric(14, 3),
    unit              varchar(5),
    unit_price        numeric(14, 6),
    confidence        double precision not null
);

create index core_pending_line_idx on core_pending_line (pending_change_id, line_no);

-- Cook events -----------------------------------------------------------------

create table core_cook_event (
    id              bigint generated by default as identity primary key,
    household_id    bigint         not null references core_household (id),
    user_id         bigint         not null references core_user (id),
    dish_name       varchar(200)   not null,
    servings        integer        not null,
    ingredient_cost numeric(12, 2) not null,
    txn_id          bigint         not null references core_txn (id),
    cooked_at       timestamp with time zone not null
);

create index core_cook_event_household_idx on core_cook_event (household_id, id);
